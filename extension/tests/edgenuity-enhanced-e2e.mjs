/**
 * Phase 5 end-to-end: a code that didn't exist yesterday, in today's photo.
 *
 * The run this suite exists for:
 *
 *   Edgenuity assignment requiring Enhanced Proof
 *     → Strict Focus Mode, youtube.com blocked for real
 *     → LockIn issues code A; the camera shows 43% *and* code A → accepted
 *     → LockIn issues code B; the camera shows 47% and the *wrong* code → refused
 *     → the camera shows 47% and code B → accepted, enhanced trust
 *     → assignment completes, Focus Mode ends, youtube.com loads
 *     → a new session is started and the previous photo is offered again → refused
 *
 * The last step is the one that decides whether Phase 5 is worth anything: a
 * frame that satisfied a completed session must be useless in the next one.
 *
 * The codes are generated by the app and are unknowable in advance, so the
 * camera frames are *rendered at capture time* to show whichever code LockIn
 * just issued. Chrome's fake video device then delivers them through the real
 * getUserMedia, so nothing about the capture path is stubbed.
 *
 * Needs: the dev server on :5173, and Chrome for Testing.
 * Run: npm run test:edgenuity-enhanced-e2e
 */
