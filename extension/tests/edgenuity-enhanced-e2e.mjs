/* ---------------- Watchdog ---------------- */

/**
 * Names the phase currently running, and kills the run if one stalls.
 *
 * Without this a hang produces an empty log and no clue where it stopped —
 * which is exactly what happened twice while writing this suite. Every phase
 * announces itself, so a stall reports the step it died in.
 */
let currentStep = 'starting up';
let stepStartedAt = Date.now();
const STEP_LIMIT_MS = 4 * 60_000;

function step(name) {
  currentStep = name;
  stepStartedAt = Date.now();
  if (VERBOSE) console.log(`  → ${name}`);
}

const watchdog = setInterval(() => {
  if (Date.now() - stepStartedAt < STEP_LIMIT_MS) return;
  console.error(
    `\nWatchdog: "${currentStep}" made no progress for ${Math.round(
      (Date.now() - stepStartedAt) / 1000,
    )}s — giving up.`,
  );
  process.exit(1);
}, 5000);
watchdog.unref();

/* ---------------- CDP ---------------- */

class CDP {
  constructor(url) {
    this.ws = new WebSocket(url);
    this.id = 0;
    this.pending = new Map();
    this.ready = new Promise((res, rej) => {
      this.ws.addEventListener('open', res);
      this.ws.addEventListener('error', rej);
    });
    this.ws.addEventListener('message', (event) => {
      const msg = JSON.parse(event.data);
      const entry = msg.id && this.pending.get(msg.id);
      if (!entry) return;
      this.pending.delete(msg.id);
      msg.error ? entry.reject(new Error(JSON.stringify(msg.error))) : entry.resolve(msg);
    });
  }
  async send(method, params = {}, sessionId) {
    await this.ready;
    const id = ++this.id;
    return new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject });
      this.ws.send(JSON.stringify({ id, method, params, sessionId }));
      setTimeout(() => {
        if (this.pending.delete(id)) reject(new Error(`CDP timeout: ${method}`));
      }, 180_000);
    });
  }
  close() {
    try {
      this.ws.close();
    } catch {
      /* already gone */
    }
  }
}

async function fetchJSON(path, tries = 60) {
  for (let i = 0; i < tries; i += 1) {
    try {
      const res = await fetch(`http://127.0.0.1:${CDP_PORT}${path}`);
      if (res.ok) return await res.json();
    } catch {
      /* not up yet */
    }
    await sleep(250);
  }
  throw new Error('Chrome DevTools endpoint never came up');
}

let browser = null;
