async function evalIn(sessionId, expression) {
  const { result } = await browser.send(
    'Runtime.evaluate',
    { expression, awaitPromise: true, returnByValue: true },
    sessionId,
  );
  if (result.exceptionDetails) {
    throw new Error(
      `eval failed: ${result.exceptionDetails.exception?.description ?? result.exceptionDetails.text}`,
    );
  }
  return result.result.value;
}

const app = (expression) => evalIn(appSession, expression);

async function openTab(url) {
  const { targetId } = (await browser.send('Target.createTarget', { url: 'about:blank' })).result;
  const { sessionId } = (
    await browser.send('Target.attachToTarget', { targetId, flatten: true })
  ).result;
  await browser.send('Page.enable', {}, sessionId);
  await browser.send('Runtime.enable', {}, sessionId);
  await browser.send('Page.navigate', { url }, sessionId);
  await sleep(1500);
  return { targetId, sessionId };
}

/* ---------------- UI helpers ---------------- */

function clickByTextExpression(text, selector = 'button') {
  return `(() => {
    const wanted = ${JSON.stringify(text)}.toLowerCase();
    const nodes = [...document.querySelectorAll(${JSON.stringify(selector)})];
    const hit = nodes.find(
      (n) => !n.disabled && (n.textContent || '').trim().toLowerCase().includes(wanted),
    );
    if (!hit) return false;
    hit.click();
    return true;
  })()`;
}

/**
 * Buttons inside the open dialog.
 *
 * Scoping matters more than it looks: the assignment panel behind the dialog
 * has its own "Cancel", which abandons the whole verification session. An
 * unscoped click found it and quietly restarted the flow.
 */
const DIALOG_BUTTON = '[role="dialog"] button';

const BUTTONS_EXPR = `[...document.querySelectorAll('button')]
  .map((b) => (b.textContent || '').trim() + (b.disabled ? ' [disabled]' : ''))
  .filter(Boolean)
  .join(' | ')`;

async function waitFor(expression, { timeout = 120_000, label = 'condition' } = {}) {
  const deadline = Date.now() + timeout;
  while (Date.now() < deadline) {
    if (await app(expression)) return true;
    await sleep(500);
  }
  const buttons = await app(BUTTONS_EXPR).catch(() => '(unreadable)');
  const dialog = await app(DIALOG_EXPR).catch(() => '');
  throw new Error(
    `Timed out waiting for ${label}\n    buttons: ${buttons}\n    dialog: ${summarise(dialog, 400)}`,
  );
}

const DIALOG_EXPR = `(() => {
  const d = document.querySelector('[role="dialog"]');
  return d ? d.innerText : '(no dialog)';
})()`;

const readState = async () =>
  JSON.parse((await app(`localStorage.getItem('lockin.state.v1')`)) ?? 'null');

/* ---------------- Camera frames, rendered on demand ---------------- */

let cameraFile = null;

/**
 * Paints an Edgenuity screen showing `percent` and `code`, and points the fake
 * camera at it.
 *
 * Rendering per capture is what lets this test photograph a code the app chose
 * at random moments earlier — the thing the whole feature turns on.
 */
async function showToCamera({ percent, code, course = 'Physical Science Semester A', variant = 0 }) {
  const spec = `custom:${percent}:${code ?? ''}:${course}:${variant}`;
  const payload = await evalIn(
    painterSession,
    `JSON.stringify(window.__exportFixture(${JSON.stringify(spec)}, ${WIDTH}, ${HEIGHT}))`,
  );
  const { i420 } = JSON.parse(payload);
  // Written aside and renamed into place: Chrome opens this file when the
  // camera starts, and a partially-written frame reads as a blank or torn
  // image, which looks exactly like a failed capture.
  const staging = `${cameraFile}.next`;
  writeFileSync(staging, y4mFromI420(i420));
  renameSync(staging, cameraFile);

  /**
   * Chrome reads this file when the camera *starts*, so a stream already
   * running keeps showing the previous frame. "Retake" reopens the camera
   * immediately, which would otherwise leave the next capture photographing
   * the frame we just replaced — closing it here forces a fresh open.
   */
  if (appSession && (await app(`!!document.querySelector('[role="dialog"] video')`))) {
    await app(clickByTextExpression('cancel', DIALOG_BUTTON));
    await sleep(500);
  }
  await sleep(900);
}

/* ---------------- Flow helpers ---------------- */

/** The code LockIn is currently showing for this phase, read from state. */
async function currentCode(phase) {
  const state = await readState();
  const challenge = state.edgenuity.challenges.find(
    (c) => c.status === 'pending' && c.phase === phase,
  );
  return challenge?.value;
}

/**
 * Opens the camera if it isn't already open, captures, waits for OCR, then
 * clicks `confirmLabel`.
 *
 * "Retake" drops straight back to the camera step rather than the guidance
 * step, so this has to cope with the shutter already being on screen.
 */
async function captureThroughUi(confirmLabel) {
  const onCameraStep = async () =>
    (await app(`!!document.querySelector('[role="dialog"] video')`)) === true;

  if (!(await onCameraStep())) {
    await waitFor(clickByTextExpression('open camera', DIALOG_BUTTON), {
      label: 'the Open camera button',
    });
    await sleep(1200);
  }
  await waitFor(clickByTextExpression('capture', DIALOG_BUTTON), {
    label: 'a live camera preview',
    timeout: 40_000,
  });
  await waitFor(
    `!!document.body.innerText.match(/Detected|couldn.t (read|confidently)|wasn.t detected/i)`,
    { label: 'the OCR result', timeout: 150_000 },
  );
  const dialog = await app(DIALOG_EXPR);
  if (VERBOSE) console.log(`    · review: ${summarise(dialog, 300)}`);
  const clicked = await app(clickByTextExpression(confirmLabel, DIALOG_BUTTON));
  await sleep(900);
  return { dialog, clicked };
}

/**
 * A capture that is *supposed* to succeed, with retakes.
 *
 * Reading four hand-sized characters off a photographed screen is not
 * deterministic — roughly one attempt in five misses on these fixtures, and a
 * real student simply takes another photo. Retrying here keeps the suite about
 * the security properties rather than about OCR luck. Refusals are never
 * retried: a wrong code must fail on the first attempt and stay failed.
 */
async function captureUntilAccepted({ percent, code, confirmLabel, attempts = 3 }) {
  let last = { dialog: '', clicked: false };
  /* Four characters read off a photographed card is not deterministic; three
     differently-framed attempts is what a student would do before giving up. */
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    // Each retake re-frames the shot, the way a student would.
    await showToCamera({ percent, code, variant: attempt - 1 });
    last = await captureThroughUi(confirmLabel);
    const detected = /verified\s*✓|verified ✓/i.test(last.dialog);
    if (last.clicked && detected) return { ...last, attempts: attempt };

    if (VERBOSE) console.log(`    · attempt ${attempt} did not read the code; retaking`);
    await app(clickByTextExpression('retake', DIALOG_BUTTON));
    await sleep(700);
  }
  return { ...last, attempts };
}

async function isBlocked(url) {
  const tab = await openTab(url);
  const href = await evalIn(tab.sessionId, 'location.href');
  await browser.send('Target.closeTarget', { targetId: tab.targetId });
  return href.startsWith('chrome-extension://');
}

