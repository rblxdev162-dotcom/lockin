#!/usr/bin/env node
/**
 * Generates the extension's origin configuration from `lockin.config.json`.
 *
 * Three places have to agree about where the LockIn web app lives, and before
 * Phase 8 all three hard-coded `http://localhost:5173`:
 *
 *   1. `extension/shared/config.js`       — ES module, read by the service worker
 *   2. `extension/shared/build-config.js` — classic script, read by the content
 *                                            script relay (which cannot import)
 *   3. `manifest.json` content_scripts.matches — where Chrome injects the relay
 *
 * All three are written here from one source so they cannot drift. The files
 * are committed with the development values, so "Load unpacked" straight from
 * the repo keeps working with no build step.
 *
 * Usage:
 *   node scripts/gen-extension-config.mjs                    # development
 *   LOCKIN_ENV=production LOCKIN_APP_ORIGIN=https://app.example.com \
 *     node scripts/gen-extension-config.mjs [--out <dir>]
 *
 * `--out` writes into a copy of the extension (used by the packaging script)
 * instead of the working tree.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Parses `--out <dir>` out of argv. */
function parseArgs(argv) {
  const out = argv.indexOf('--out');
  return { outDir: out !== -1 ? resolve(argv[out + 1]) : resolve(ROOT, 'extension') };
}

/**
 * Origins must be a bare scheme+host(+port) with no path, and http:// is only
 * acceptable for loopback — a production build served over plain http would
 * also break the camera, which needs a secure context.
 */
export function validateOrigin(value) {
  let url;
  try {
    url = new URL(value);
  } catch {
    return `"${value}" is not a URL`;
  }
  if (url.origin !== value.replace(/\/$/, '')) {
    return `"${value}" must be a bare origin (scheme://host[:port]), with no path`;
  }
  if (url.protocol !== 'https:' && url.protocol !== 'http:') {
    return `"${value}" must use http:// or https://`;
  }
  const loopback = url.hostname === 'localhost' || url.hostname === '127.0.0.1' || url.hostname === '[::1]';
  if (url.protocol === 'http:' && !loopback) {
    return `"${value}" uses http:// on a non-loopback host; Edgenuity's camera needs a secure context`;
  }
  return null;
}

/** Chrome content-script match pattern for an origin. */
export function matchPattern(origin) {
  return `${origin}/*`;
}

export function resolveConfig(env = process.env) {
  const raw = JSON.parse(readFileSync(resolve(ROOT, 'lockin.config.json'), 'utf8'));
  const name = env.LOCKIN_ENV === 'production' ? 'production' : 'development';
  const entry = raw[name];
  if (!entry) throw new Error(`lockin.config.json has no "${name}" section`);

  const origins = [...(entry.origins ?? [])];
  // A production origin is supplied at build time rather than committed: no
  // production origin exists yet, and inventing one would ship a dead default.
  if (env.LOCKIN_APP_ORIGIN) {
    for (const extra of env.LOCKIN_APP_ORIGIN.split(',').map((s) => s.trim()).filter(Boolean)) {
      if (!origins.includes(extra)) origins.push(extra);
    }
  }

  if (origins.length === 0) {
    throw new Error(
      `No app origin configured for "${name}". Set LOCKIN_APP_ORIGIN, e.g.\n` +
        `  LOCKIN_ENV=production LOCKIN_APP_ORIGIN=https://lockin.example.com npm run package:extension`,
    );
  }
  for (const origin of origins) {
    const problem = validateOrigin(origin);
    if (problem) throw new Error(`Bad origin in ${name} config: ${problem}`);
  }

  const appPath = entry.appPath ?? '/home';
  return { env: name, origins, appUrl: `${origins[0]}${appPath}` };
}

const BANNER = `/* GENERATED by scripts/gen-extension-config.mjs — do not edit by hand.\n   Source of truth: lockin.config.json (+ LOCKIN_ENV / LOCKIN_APP_ORIGIN). */`;

function esmSource(config) {
  return `${BANNER}
/**
 * Where the LockIn web app is allowed to live.
 *
 * The content script refuses to relay messages from any origin not in this
 * list, which is what stops a random page from turning Focus Mode off. The
 * service worker checks it a second time on the sender's real origin.
 */
export const BUILD_ENV = ${JSON.stringify(config.env)};

export const ALLOWED_APP_ORIGINS = ${JSON.stringify(config.origins, null, 2)};

/** Fallback used by the popup / block page for the "Open LockIn" button. */
export const DEFAULT_APP_URL = ${JSON.stringify(config.appUrl)};

export function isAllowedOrigin(origin) {
  return ALLOWED_APP_ORIGINS.includes(origin);
}
`;
}

function classicSource(config) {
  return `${BANNER}
/**
 * Classic-script twin of shared/config.js.
 *
 * content/bridge.js runs as a classic content script and cannot use \`import\`,
 * so this file is listed ahead of it in manifest.json's content_scripts. Both
 * files share one isolated world, so the assignment below is visible there and
 * nowhere else on the page.
 */
globalThis.__LOCKIN_BUILD__ = {
  BUILD_ENV: ${JSON.stringify(config.env)},
  ALLOWED_APP_ORIGINS: ${JSON.stringify(config.origins)},
  DEFAULT_APP_URL: ${JSON.stringify(config.appUrl)},
};
`;
}

export function applyToManifest(manifest, config) {
  const next = structuredClone(manifest);
  const relay = next.content_scripts?.find((entry) => entry.js?.includes('content/bridge.js'));
  if (!relay) throw new Error('manifest.json has no content script entry for content/bridge.js');
  relay.matches = config.origins.map(matchPattern);
  return next;
}

function main() {
  const { outDir } = parseArgs(process.argv.slice(2));
  const config = resolveConfig();

  writeFileSync(resolve(outDir, 'shared/config.js'), esmSource(config));
  writeFileSync(resolve(outDir, 'shared/build-config.js'), classicSource(config));

  const manifestPath = resolve(outDir, 'manifest.json');
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  writeFileSync(manifestPath, `${JSON.stringify(applyToManifest(manifest, config), null, 2)}\n`);

  console.log(
    `[LockIn] extension config → ${config.env}: ${config.origins.join(', ')} (app ${config.appUrl})`,
  );
}

if (import.meta.url === `file://${process.argv[1]}`) main();
